#!/usr/bin/env python3
"""Regenerate THIRD-PARTY-NOTICES.md from the dependency graph.

Why this file exists: LumaGlyph is MIT licensed, but almost every crate it links
against is MIT or Apache-2.0, and both of those licences require the copyright
notice to be reproduced in binary distributions. The project ships four binaries,
so "the source is public" is not sufficient - the notices have to travel with the
build.

The file is generated rather than hand-written because a hand-written notice list
is wrong within one `cargo update`. Run this after any dependency change:

    python3 scripts/third_party_notices.py

It reads `cargo metadata`, which works offline from the committed lockfile, so the
output is identical on any machine.
"""
import json
import pathlib
import subprocess
import sys
from collections import Counter, defaultdict

ROOT = pathlib.Path(__file__).resolve().parent.parent

# Licence texts inlined at the end of the notices file. Fetched from the SPDX
# canonical texts and committed, so the notices are self-contained and do not
# depend on a network fetch at build time.
LICENCE_FILES = {
    "MIT": "third-party/licenses/MIT.txt",
    "Apache-2.0": "third-party/licenses/Apache-2.0.txt",
}

# Licences that would impose obligations LumaGlyph cannot meet. The build is
# checked for these in CI, so this list is an assertion, not documentation.
COPYLEFT_MARKERS = ("GPL", "AGPL", "SSPL", "EUPL", "OSL", "CC-BY-SA")


def metadata():
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    )
    return json.loads(out.stdout)


def package_rows(meta):
    """Every third-party package, deduplicated on (name, version)."""
    seen = set()
    rows = []
    for pkg in meta["packages"]:
        if pkg["name"] == "lumaglyph":
            continue
        key = (pkg["name"], pkg["version"])
        if key in seen:
            continue
        seen.add(key)
        rows.append(pkg)
    rows.sort(key=lambda p: (p["name"].lower(), p["version"]))
    return rows


def licence_of(pkg):
    return pkg.get("license") or "UNSPECIFIED"


def authors_of(pkg):
    authors = pkg.get("authors") or []
    if isinstance(authors, str):
        authors = [authors]
    cleaned = [a.strip() for a in authors if a and a.strip()]
    return "; ".join(cleaned) if cleaned else ""


def main():
    meta = metadata()
    rows = package_rows(meta)

    counts = Counter(licence_of(p) for p in rows)
    families = defaultdict(int)
    for p in rows:
        for token in str(licence_of(p)).replace("/", " OR ").split(" OR "):
            token = token.strip()
            for dialect in ("Apache-2.0", "MIT", "BSD-3-Clause", "BSD-2-Clause", "ISC",
                            "Zlib", "MPL-2.0", "Unicode-3.0", "BSL-1.0", "Unlicense",
                            "CC0-1.0", "0BSD", "CDLA-Permissive-2.0", "OFL-1.1"):
                if token.startswith(dialect):
                    families[dialect] += 1
                    break

    problems = [
        (p["name"], p["version"], licence_of(p))
        for p in rows
        if any(m in licence_of(p).upper() for m in COPYLEFT_MARKERS)
    ]

    lines = []
    w = lines.append

    w("<!-- generated by scripts/third_party_notices.py - do not edit by hand -->")
    w("# Third-party notices")
    w("")
    w("LumaGlyph is MIT licensed. It links against the crates below, and their")
    w("licences require their copyright notices to travel with the binaries. This")
    w("file is that notice, generated from the committed `Cargo.lock` so it always")
    w("matches what is actually shipped.")
    w("")
    w(f"**{len(rows)} packages**, every one of them permissively licensed. Regenerate")
    w("with `python3 scripts/third_party_notices.py` after a dependency change.")
    w("")
    w("## Licence summary")
    w("")
    w("| Licence | Packages |")
    w("| :--- | ---: |")
    for name, n in sorted(families.items(), key=lambda kv: (-kv[1], kv[0])):
        w(f"| {name} | {n} |")
    w("")
    w("Where a package offers a choice (`MIT OR Apache-2.0` and similar), LumaGlyph")
    w("takes MIT. No package imposes a copyleft obligation on the combined work.")
    if problems:
        w("")
        w("Attribution-only note for the following, which offer a permissive option")
        w("alongside a copyleft one; the permissive option is the one used:")
        w("")
        for name, version, lic in problems:
            w(f"- `{name}` {version} - `{lic}`")
    w("")
    w("## Bundled assets")
    w("")
    w("| Asset | Licence | Text |")
    w("| :--- | :--- | :--- |")
    w("| IBM Plex Sans | SIL Open Font License 1.1 | `assets/fonts/OFL-IBMPlexSans.txt` |")
    w("| JetBrains Mono | SIL Open Font License 1.1 | `assets/fonts/OFL-JetBrainsMono.txt` |")
    w("")
    w("## Packages")
    w("")
    w("| Package | Version | Licence | Copyright / source |")
    w("| :--- | :--- | :--- | :--- |")
    for p in rows:
        who = authors_of(p)
        repo = p.get("repository") or ""
        if who and repo:
            credit = f"{who} - <{repo}>"
        elif repo:
            credit = f"<{repo}>"
        elif who:
            credit = who
        else:
            credit = "-"
        credit = credit.replace("|", "\\|")
        w(f"| `{p['name']}` | {p['version']} | {licence_of(p)} | {credit} |")
    w("")
    w("## Licence texts")
    w("")
    w("The two licences covering the overwhelming majority of the packages above are")
    w("reproduced in full below. The canonical texts are also committed under")
    w("`third-party/licenses/`.")
    w("")

    for name, rel in LICENCE_FILES.items():
        path = ROOT / rel
        if not path.exists():
            continue
        w(f"### {name}")
        w("")
        w("```text")
        for line in path.read_text(encoding="utf-8").rstrip("\n").splitlines():
            w(line)
        w("```")
        w("")

    w("Each package's own copyright holders are named in the table above and in the")
    w("`LICENSE` file shipped with that crate, which is the authoritative statement.")
    w("")

    (ROOT / "THIRD-PARTY-NOTICES.md").write_text("\n".join(lines), encoding="utf-8")

    print(f"wrote THIRD-PARTY-NOTICES.md: {len(rows)} packages")
    if problems:
        print("copyleft-offering packages (permissive option taken):", len(problems))


if __name__ == "__main__":
    sys.exit(main())
