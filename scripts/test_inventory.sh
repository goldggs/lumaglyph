#!/usr/bin/env bash
# Regenerate the executed-test inventory used by docs/TESTING.md.
#
# Writes a markdown fragment listing every suite, the number of test functions it
# declares, and the number of cases it actually runs. Keep the file in the repo so
# the claim "N tests" is always checkable rather than aspirational.
#
# Usage:
#   ./scripts/test_inventory.sh            # print to stdout
#   ./scripts/test_inventory.sh --write    # update docs/TEST-INVENTORY.md
#   ./scripts/test_inventory.sh --check    # exit 1 if the committed file is stale
#
# --check is what CI runs, so the published counts cannot drift away from the code.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

OUT="${1:-}"

collect() {
  echo "<!-- generated by scripts/test_inventory.sh - do not edit by hand -->"
  echo "# Test inventory"
  echo
  echo "Counted from \`cargo test -- --list\`. Regenerate with \`./scripts/test_inventory.sh --write\`."
  echo
  echo "| Suite | Test functions | Cases run |"
  echo "| :--- | ---: | ---: |"

  local total_fn=0 total_cases=0
  # Unit tests live in the library target; every tests/*.rs is its own target.
  for target in lib $(ls tests/*.rs | sed 's#tests/##; s#\.rs$##'); do
    local listing
    if [ "$target" = "lib" ]; then
      listing="$(cargo test --release --lib -- --list 2>/dev/null || true)"
    else
      listing="$(cargo test --release --test "$target" -- --list 2>/dev/null || true)"
    fi
    local cases
    cases="$(printf '%s\n' "$listing" | grep -c ': test$' || true)"
    local fns
    if [ "$target" = "lib" ]; then
      fns="$(grep -rho '#\[test\]' src/*.rs | wc -l | tr -d ' ')"
    else
      fns="$(grep -c '#\[test\]' "tests/$target.rs" || true)"
    fi
    [ "$cases" = "0" ] && continue
    total_fn=$((total_fn + fns))
    total_cases=$((total_cases + cases))
    echo "| \`$target\` | $fns | $cases |"
  done
  echo "| **total** | **$total_fn** | **$total_cases** |"
  echo
}

case "$OUT" in
  --write)
    collect > docs/TEST-INVENTORY.md
    echo "wrote docs/TEST-INVENTORY.md"
    ;;
  --check)
    tmp="$(mktemp)"
    collect > "$tmp"
    if ! diff -u docs/TEST-INVENTORY.md "$tmp"; then
      echo >&2
      echo "docs/TEST-INVENTORY.md is out of date." >&2
      echo "Run ./scripts/test_inventory.sh --write and commit the result." >&2
      rm -f "$tmp"
      exit 1
    fi
    rm -f "$tmp"
    echo "docs/TEST-INVENTORY.md is up to date"
    ;;
  *)
    collect
    ;;
esac
